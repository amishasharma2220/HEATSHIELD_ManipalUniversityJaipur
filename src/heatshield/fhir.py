"""Export twin forecasts as HL7 FHIR R4 resources.

FHIR R4 is the standard used for health-record exchange by India's Ayushman Bharat Digital Mission
(ABDM). Exporting the forecast as a FHIR `RiskAssessment` (plus the twin's estimated core
temperature as an `Observation`) means a hospital system could receive HEATSHIELD output without
custom integration. Everything exported here is synthetic and marked as such.
"""
from __future__ import annotations

import json
import uuid

import pandas as pd

RISK_SYSTEM = "http://terminology.hl7.org/CodeSystem/risk-probability"
OUTCOME_TEXT = "Heat strain within 24 h: Physiological Strain Index >= 7 or core temperature >= 39.0 C"
SYNTHETIC_TAG = {"system": "http://terminology.hl7.org/CodeSystem/v3-ActReason", "code": "HTEST",
                 "display": "test health data"}


def _qualitative(p: float) -> dict:
    code = "high" if p >= 0.5 else "moderate" if p >= 0.2 else "low"
    return {"coding": [{"system": RISK_SYSTEM, "code": code, "display": code.capitalize() + " likelihood"}]}


def _iso(ts) -> str:
    return pd.Timestamp(ts).tz_localize("Asia/Kolkata").isoformat()


def patient_resource(row: pd.Series, pid: str) -> dict:
    name = str(row.get("name", pid)).split(" ", 1)
    return {"resourceType": "Patient", "id": pid, "meta": {"security": [SYNTHETIC_TAG]},
            "name": [{"given": [name[0]], "family": name[-1] if len(name) > 1 else ""}],
            "gender": {"M": "male", "F": "female"}.get(str(row.get("sex", "")), "unknown"),
            "address": [{"city": str(row.get("city", "")), "country": "IN"}]}


def risk_assessment(pid: str, issued, window_start, window_end, p_event: float, peak_psi: float,
                    high_window: tuple | None = None, drivers: list[str] | None = None,
                    mitigation: str | None = None) -> dict:
    note = [f"Predicted peak PSI {peak_psi:.1f}."]
    if high_window:
        note.append(f"Highest-risk window {pd.Timestamp(high_window[0]):%H:%M}-{pd.Timestamp(high_window[1]):%H:%M}.")
    if drivers:
        note.append("Main drivers: " + "; ".join(drivers) + ".")
    note.append("Generated by a research prototype on SYNTHETIC data. Not for clinical use.")
    res = {"resourceType": "RiskAssessment", "id": str(uuid.uuid5(uuid.NAMESPACE_URL, f"{pid}/{issued}")),
           "meta": {"security": [SYNTHETIC_TAG]}, "status": "preliminary",
           "subject": {"reference": f"Patient/{pid}"}, "occurrenceDateTime": _iso(issued),
           "method": {"text": "HEATSHIELD medication-aware digital twin (particle filter + physiological model)"},
           "prediction": [{"outcome": {"text": OUTCOME_TEXT}, "probabilityDecimal": round(float(p_event), 3),
                           "qualitativeRisk": _qualitative(p_event),
                           "whenPeriod": {"start": _iso(window_start), "end": _iso(window_end)}}],
           "note": [{"text": " ".join(note)}]}
    if mitigation:
        res["mitigation"] = mitigation
    return res


def core_temp_observation(pid: str, when, tc: float, tc_sd: float) -> dict:
    return {"resourceType": "Observation", "id": str(uuid.uuid5(uuid.NAMESPACE_URL, f"{pid}/tc/{when}")),
            "meta": {"security": [SYNTHETIC_TAG]}, "status": "preliminary",
            "category": [{"coding": [{"system": "http://terminology.hl7.org/CodeSystem/observation-category",
                                      "code": "vital-signs", "display": "Vital Signs"}]}],
            "code": {"coding": [{"system": "http://loinc.org", "code": "8310-5", "display": "Body temperature"}],
                     "text": "Core body temperature (estimated by digital twin, not measured)"},
            "subject": {"reference": f"Patient/{pid}"}, "effectiveDateTime": _iso(when),
            "valueQuantity": {"value": round(float(tc), 2), "unit": "Cel", "system": "http://unitsofmeasure.org",
                              "code": "Cel"},
            "method": {"text": "Estimated from wearable heart rate, skin temperature, weather and EHR"},
            "note": [{"text": f"90% interval +/- {1.645 * tc_sd:.2f} C"}]}


def bundle(resources: list[dict]) -> dict:
    return {"resourceType": "Bundle", "type": "collection", "meta": {"security": [SYNTHETIC_TAG]},
            "entry": [{"fullUrl": f"urn:uuid:{uuid.uuid5(uuid.NAMESPACE_URL, r['resourceType'] + '/' + r['id'])}",
                       "resource": r} for r in resources]}


def dumps(obj: dict) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False)
